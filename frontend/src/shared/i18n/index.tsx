export type TranslationKey = keyof typeof translations.en;
export type TranslationValues = Record<string, string | number>;
export type TFunction = (key: TranslationKey, values?: TranslationValues) => string;

const I18nContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: TFunction;
} | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const savedLanguage = localStorage.getItem("kg-language");
    return savedLanguage === "pl" ? "pl" : "en";
  });
  const value = useMemo(
    () => ({
      language,
      setLanguage: (nextLanguage: Language) => {
        localStorage.setItem("kg-language", nextLanguage);
        setLanguage(nextLanguage);
      },
      t: (key: TranslationKey, values?: TranslationValues) => interpolate(translations[language][key], values),
    }),
    [language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

function interpolate(template: string, values?: TranslationValues) {
  if (!values) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, key) => (values[key] === undefined ? match : String(values[key])));
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}
